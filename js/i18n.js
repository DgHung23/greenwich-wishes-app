    var STORE_KEY = 'gw_lang';
    var current = 'vi';
    try { current = localStorage.getItem(STORE_KEY) || 'vi'; } catch (e) { }
    if (!DICT[current]) current = 'vi';

    function t(key, vars) {
        var s = (DICT[current] && DICT[current][key]) || DICT.vi[key] || key;
        if (vars) Object.keys(vars).forEach(function (k) { s = s.replace('{' + k + '}', vars[k]); });
        return s;
    }

    function apply(root) {
        root = root || document;
        root.querySelectorAll('[data-i18n]').forEach(function (el) { el.innerHTML = t(el.getAttribute('data-i18n')); });
        root.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) { el.placeholder = t(el.getAttribute('data-i18n-placeholder')); });
        root.querySelectorAll('[data-i18n-title]').forEach(function (el) { el.title = t(el.getAttribute('data-i18n-title')); });
        document.documentElement.lang = current;
        document.title = t('page.title');
        document.querySelectorAll('.lang-btn').forEach(function (b) { b.classList.toggle('active', b.dataset.lang === current); });
    }

    var listeners = [];
    window.i18n = {
        t: t,
        apply: apply,
        get lang() { return current; },
        onChange: function (fn) { listeners.push(fn); },
        switch: function (lang) {
            if (!DICT[lang] || lang === current) return;
            current = lang;
            try { localStorage.setItem(STORE_KEY, lang); } catch (e) { }
            apply();
            listeners.forEach(function (fn) { fn(lang); });
        }
    };
    document.addEventListener('DOMContentLoaded', function () { apply(); });
